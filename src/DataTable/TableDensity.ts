/**
 * Row density of the desktop table: `Comfortable` is the default rhythm, `Dense` gives 36 px rows and a 34 px header band,
 * `Compact` is the console ledger look (34 px rows, 28 px header band, 13 px cells, 11 px tracked header, 10 px cell gutters).
 */
export const enum TableDensity {
  Comfortable = 'comfortable',
  Dense = 'dense',
  Compact = 'compact',
}
